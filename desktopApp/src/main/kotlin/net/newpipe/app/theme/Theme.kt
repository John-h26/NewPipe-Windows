private val blackScheme = darkScheme.copy(surface = Color.Black, background = Color.Black)

@Composable
fun AppTheme(settings: AppSettings, content: @Composable () -> Unit) {
    val colorScheme = when (settings.theme) {
        AppSettings.THEME_LIGHT -> lightScheme
        AppSettings.THEME_DARK -> darkScheme
        AppSettings.THEME_BLACK -> blackScheme
        else -> if (isSystemInDarkTheme()) darkScheme else lightScheme
    }
    MaterialTheme(colorScheme = colorScheme, content = content)
}
